export type WatchSource = {
  name: string;
  url: string;
  type: "github" | "rss" | "page";
  topic: string;
  interval_minutes: number;
};
const release = (
  repo: string,
  name: string,
  topic: string,
  minutes = 240,
): WatchSource => ({
  name: name + " releases",
  url: "https://api.github.com/repos/" + repo + "/releases?per_page=10",
  type: "github",
  topic,
  interval_minutes: minutes,
});
const page = (name: string, url: string, topic: string): WatchSource => ({
  name,
  url,
  topic,
  type: "page",
  interval_minutes: 720,
});
